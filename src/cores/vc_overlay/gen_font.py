#!/usr/bin/env python3
"""gen_font.py - Generate vc_font.h: an 8x16 bitmap font for the timestamp characters.

Renders the 13 glyphs the timestamp needs ('0'-'9', '-', ':', ' ') from DejaVu Sans Mono
(a permissively licensed font) into a C header, so the HLS code has no runtime dependency
on a font file. Re-run only if you want to change the look:

    python3 gen_font.py [path/to/DejaVuSansMono.ttf] > vc_font.h
"""
import sys
from PIL import Image, ImageDraw, ImageFont

CHARS = "0123456789-: "
W, H = 8, 16
path = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf"
font = ImageFont.truetype(path, 14)

print("// vc_font.h - GENERATED by gen_font.py from DejaVu Sans Mono Bold. Do not edit by hand.")
print("// 8x16 glyphs, one byte per row, bit 7 = leftmost pixel.")
print("#ifndef VC_FONT_H\n#define VC_FONT_H\n")
print("// glyph index: 0-9 digits, 10 '-', 11 ':', 12 ' '")
print("static const unsigned char vc_font[13][16] = {")
# one common baseline for every glyph: centre the digit '0' vertically in the cell
zb = font.getbbox("0")
y_off = (H - (zb[3] - zb[1])) // 2 - zb[1]
for ch in CHARS:
    im = Image.new("1", (W, H), 0)
    d = ImageDraw.Draw(im)
    adv = d.textlength(ch, font=font)
    d.text((int(round((W - adv) / 2)), y_off), ch, font=font, fill=1)
    rows = []
    for y in range(H):
        v = 0
        for x in range(W):
            if im.getpixel((x, y)):
                v |= 0x80 >> x
        rows.append(v)
    print("    {" + ", ".join("0x%02X" % r for r in rows) + "},  // '%s'" % ch)
print("};\n\n#endif")
