#!/usr/bin/env bash
#
# gen_vivado_tcl.sh - Generate standalone Vivado Tcl that recreates the vidcap workspace and its IP.
#
# Writes, under workspace/vivado/generated/ (untracked):
#   vidcap_bd_generated.tcl        the block design (write_bd_tcl, with layout)
#   vidcap_project_generated.tcl   the whole Vivado project (write_project_tcl), sources referenced in place
#   add_hls_ip.tcl                 adds the packaged vidcap HLS IPs (vc_filter, vc_overlay, vc_snapshot)
#                                  to the project's IP catalogue
#
# They are produced from the project that `make overlay` (or this script, if it is missing) builds,
# so they always match the current sources. Re-create the project from them with:
#
#   vivado -mode batch -source workspace/vivado/generated/vidcap_project_generated.tcl
#
# Prerequisites for a missing project: src/overlay/scripts/fetch_refs.sh and `make ip`.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
WS="$ROOT/workspace/vivado"
OUT="$WS/generated"
PROJ="$WS/vidcap_proj/vidcap.xpr"

if [ -z "${XILINX_VIVADO:-}" ]; then
  set +eu; source "${AMD_ROOT:-$HOME/AMD}/2025.2/Vitis/settings64.sh" >/dev/null 2>&1; set -eu
fi
mkdir -p "$OUT"
cd "$WS"            # keeps Vivado's scratch files out of the source tree

if [ ! -f "$PROJ" ]; then
  echo "no Vivado project yet: creating it (block design only, no synthesis)"
  vivado -mode batch -nolog -nojournal -source "$ROOT/src/overlay/scripts/build.tcl" -tclargs "$ROOT" bd >/dev/null
fi

GEN="$OUT/_generate.tcl"
cat > "$GEN" <<TCL
set proj  "$PROJ"
set out   "$OUT"
set ws    "$WS"
set root  "$ROOT"

open_project \$proj
open_bd_design [get_files vidcap.bd]
write_bd_tcl -force -include_layout \$out/vidcap_bd_generated.tcl
close_bd_design [current_bd_design]

write_project_tcl -force -target_proj_dir \$ws/vidcap_regen \$out/vidcap_project_generated.tcl

# The script resolves its source paths relative to the original project folder but defaults that
# base to the current directory. Pin it, so the script works from any working directory.
set pf [open \$out/vidcap_project_generated.tcl r]; set body [read \$pf]; close \$pf
set body [string map [list "set origin_dir \".\"" "set origin_dir \"\$ws/vidcap_proj\"" \\
                           "create_project \\\${_xil_proj_name_} " "create_project -force \\\${_xil_proj_name_} "] \$body]
set pf [open \$out/vidcap_project_generated.tcl w]; puts -nonewline \$pf \$body; close \$pf

# IP catalogue script: one line per packaged HLS IP found in the build or generated trees
set fh [open \$out/add_hls_ip.tcl w]
puts \$fh "# add_hls_ip.tcl - GENERATED by scripts/gen_vivado_tcl.sh. Adds the vidcap HLS IPs to the open project."
puts \$fh "set repo \${ws}/ip_repo"
puts \$fh "file mkdir \\\$repo"
foreach core {vc_filter vc_overlay vc_snapshot} {
    set zips [concat [glob -nocomplain \$root/workspace/vitishls/generated/ip/\$core.zip] \\
                     [glob -nocomplain \$root/workspace/vitishls/\${core}_build/work/\$core.zip]]
    if {[llength \$zips] == 0} { puts "warning: no packaged IP for \$core (run make hls-package or scripts/gen_hls_tcl.py)"; continue }
    puts \$fh "update_ip_catalog -add_ip [lindex \$zips 0] -repo_path \\\$repo"
}
puts \$fh "update_ip_catalog -rebuild"
close \$fh

close_project
puts "GENERATED-VIVADO-DONE"
TCL

vivado -mode batch -nolog -nojournal -source "$GEN" 2>&1 | grep -E "GENERATED-VIVADO-DONE|^ERROR|warning:" || true
rm -f "$GEN"
ls -l "$OUT"/*.tcl
