#!/usr/bin/env python3
"""gen_hls_tcl.py - Generate standalone Vitis HLS Tcl scripts for the vidcap cores.

Each core's settings live in one place, src/cores/<core>/hls.cfg.in (also used by run_hls.sh). This
script reads that template and writes plain Tcl that recreates the HLS workspace and runs the flow,
so a core can be rebuilt without Make or the config-file runner:

    workspace/vitishls/generated/<core>_sim.tcl     small frame: csim, csynth, cosim
    workspace/vitishls/generated/<core>_build.tcl   full 1280x720, free-running: csynth + IP export
    workspace/vitishls/generated/run_all.sh         runs every generated script

Run a script with:   vitis-run --mode hls --tcl workspace/vitishls/generated/vc_filter_build.tcl
(the build script leaves the packaged IP at workspace/vitishls/generated/ip/<core>.zip).

Usage: gen_hls_tcl.py [core ...]        (default: every core that has an hls.cfg.in)
"""
import argparse
import os
import re
import stat
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
CORES_DIR = os.path.join(ROOT, "src", "cores")
OUT = os.path.join(ROOT, "workspace", "vitishls", "generated")
COMMON = os.path.join(CORES_DIR, "vc_common")


def parse_cfg(text):
    """Return ({top-level key: value}, {[hls] key: value}) from a Vitis config file."""
    top, hls, section = {}, {}, None
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        m = re.match(r"\[(\w+)\]", line)
        if m:
            section = m.group(1)
            continue
        k, _, v = line.partition("=")
        (hls if section == "hls" else top)[k.strip()] = v.strip()
    return top, hls


def tcl_quote(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$").replace("[", "\\[") + '"'


def sim_dims(core_dir):
    path = os.path.join(core_dir, "sim_dims")
    if os.path.exists(path):
        w, h = open(path).read().split()
        return int(w), int(h)
    return 64, 48


def substitute(text, core_dir, w, h, ctrl):
    return (text.replace("@SRC@", core_dir).replace("@COMMON@", COMMON)
                .replace("@W@", str(w)).replace("@H@", str(h)).replace("@CTRL@", ctrl)
                .replace("@SNAP_DEPTH@", str(w * 3 // 8 * h)))


def render(core, core_dir, variant, cfg_text):
    sim = variant == "sim"
    w, h = sim_dims(core_dir) if sim else (1280, 720)
    text = substitute(cfg_text, core_dir, w, h, "" if sim else "-DVC_CTRL_NONE")
    top, hls = parse_cfg(text)
    clock = hls.get("clock", "10ns").replace("ns", "")
    proj = os.path.join(OUT, "proj", f"{core}_{variant}")
    ip_dir = os.path.join(OUT, "ip")
    lines = [
        f"# {core}_{variant}.tcl - GENERATED by scripts/gen_hls_tcl.py from src/cores/{core}/hls.cfg.in.",
        "# Do not edit; change the template and regenerate.",
        f"# Frame size {w}x{h}; {'simulation build (block-level handshake)' if sim else 'production build (free-running, ap_ctrl_none)'}.",
        "",
        f"open_project -reset {tcl_quote(proj)}",
        f"set_top {hls['syn.top']}",
        f"add_files {tcl_quote(hls['syn.file'])} -cflags {tcl_quote(hls.get('syn.cflags', '').strip())}",
    ]
    if "tb.file" in hls:
        lines.append(f"add_files -tb {tcl_quote(hls['tb.file'])} -cflags {tcl_quote(hls.get('tb.cflags', '').strip())}")
    lines += [
        f"open_solution -reset -flow_target {hls.get('flow_target', 'vivado')} sol1",
        f"set_part {{{top.get('part', 'xc7z020clg400-1')}}}",
        f"create_clock -period {clock} -name default",
        f"set_clock_uncertainty {hls.get('clock_uncertainty', '27%')}",
        "",
    ]
    if sim:
        lines += ["csim_design", "csynth_design", "cosim_design", "puts \"GENERATED-FLOW-DONE\"", "exit"]
    else:
        name = hls.get("package.ip.name", core)
        lines += [
            "csynth_design",
            f"file mkdir {tcl_quote(ip_dir)}",
            "export_design -format ip_catalog -rtl verilog "
            f"-ipname {name} -vendor {hls.get('package.ip.vendor', 'vidcap')} "
            f"-library {hls.get('package.ip.library', 'vidcap')} -version {hls.get('package.ip.version', '1.0')} "
            f"-display_name {tcl_quote(hls.get('package.ip.display_name', name))} "
            f"-output {tcl_quote(os.path.join(ip_dir, core + '.zip'))}",
            "puts \"GENERATED-FLOW-DONE\"",
            "exit",
        ]
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("cores", nargs="*", help="core names (default: all with an hls.cfg.in)")
    args = ap.parse_args()

    cores = args.cores or sorted(d for d in os.listdir(CORES_DIR)
                                 if os.path.exists(os.path.join(CORES_DIR, d, "hls.cfg.in")))
    if not cores:
        sys.exit("no cores with an hls.cfg.in found")
    os.makedirs(OUT, exist_ok=True)
    written = []
    for core in cores:
        core_dir = os.path.join(CORES_DIR, core)
        cfg = os.path.join(core_dir, "hls.cfg.in")
        if not os.path.exists(cfg):
            sys.exit(f"{core}: no hls.cfg.in")
        cfg_text = open(cfg).read()
        for variant in ("sim", "build"):
            path = os.path.join(OUT, f"{core}_{variant}.tcl")
            with open(path, "w") as fh:
                fh.write(render(core, core_dir, variant, cfg_text))
            written.append((core, variant, path))
            print(path)

    runner = os.path.join(OUT, "run_all.sh")
    with open(runner, "w") as fh:
        fh.write("#!/usr/bin/env bash\n# GENERATED by scripts/gen_hls_tcl.py: run every generated HLS script.\n"
                 "set -euo pipefail\n"
                 'if [ -z "${XILINX_VITIS:-}" ]; then set +eu; source "${AMD_ROOT:-$HOME/AMD}/2025.2/Vitis/settings64.sh" >/dev/null 2>&1; set -eu; fi\n'
                 'cd "$(dirname "$0")"\n')
        for core, variant, path in written:
            fh.write(f'echo "== {core} {variant}"; vitis-run --mode hls --tcl "{path}" 2>&1 | tee "{core}_{variant}.log" | grep -E "GENERATED-FLOW-DONE|TEST (PASSED|FAILED)|co-simulation finished|ERROR" || true\n')
    os.chmod(runner, os.stat(runner).st_mode | stat.S_IXUSR)
    print(runner)


if __name__ == "__main__":
    main()
